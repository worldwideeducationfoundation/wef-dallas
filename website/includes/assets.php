<?php

declare(strict_types=1);

/**
 * Asset URL and <img> helpers.
 *
 * Two problems this solves, both of which were live.
 *
 * ---------------------------------------------------------------------------
 * 1. Cache busting that cannot be forgotten
 * ---------------------------------------------------------------------------
 * public/.htaccess serves every .css and .js with
 *
 *     Cache-Control: public, max-age=31536000, immutable
 *
 * "immutable" means a browser that has the file will not revalidate it for a
 * year — not on reload, not on a hard refresh. That is safe only when a change
 * ships under a different URL, and the site was half doing that: styles.css
 * carried a hand-typed "?v=4.3" while uiverse-cards.css and impact-goals-new.css
 * carried nothing at all. Editing either of those two would have been invisible
 * to every returning visitor for a year, with no way to push a fix.
 *
 * asset() derives the version from the file's own mtime, so the URL changes
 * when — and only when — the file does. Nothing to remember and nothing to bump
 * by hand.
 *
 * ---------------------------------------------------------------------------
 * 2. Serving a 1800px photo to a 360px phone
 * ---------------------------------------------------------------------------
 * imageTag() emits width descriptors pointing at the variants generated by
 * extras/tools/optimize-images.php, so a phone downloads the 480px copy (~40 KB)
 * instead of the original (~613 KB).
 *
 * srcset deliberately lists only the ORIGINAL format. The WebP twins beside
 * each variant are picked up by the content-negotiation rule in
 * public/.htaccess, which swaps the bytes per-request based on the Accept
 * header. Writing both formats into a <picture> element here would double the
 * markup to express something the server already handles for every image on
 * the site, including CSS backgrounds that markup cannot reach at all.
 */

/**
 * Root-relative URL with a cache-busting version derived from the file itself.
 *
 * @param string $path Path below public/, e.g. 'css/styles.css'.
 */
function asset(string $path): string
{
    static $versions = [];

    $path = ltrim($path, '/');

    if (!isset($versions[$path])) {
        $abs = publicPath($path);
        // A missing file still returns a usable URL: a broken stylesheet link
        // is a visible, debuggable failure, whereas a fatal here would take the
        // whole page down over a typo in an asset name.
        $versions[$path] = is_file($abs) ? substr(dechex(filemtime($abs)), -8) : '0';
    }

    return $path . '?v=' . $versions[$path];
}

/**
 * Absolute filesystem path for something below public/.
 */
function publicPath(string $path): string
{
    return dirname(__DIR__) . '/public/' . ltrim($path, '/');
}

/**
 * URL path the public site is served from, with a trailing slash: '/' on the
 * live domain, '/WEF/' or '/WEF/website/public/' under XAMPP.
 *
 * SCRIPT_NAME alone is not the answer. On Hostinger the uploaded folder sits
 * in public_html and its .htaccess forwards every request into public/, so a
 * page runs as /public/index.php while the visitor's address is /. Links and
 * image URLs built from SCRIPT_NAME would all gain a /public/ segment. When
 * the request did not address public/ directly, the served base is the part
 * of the script's directory that the requested path shares with it.
 */
function siteBasePath(): string
{
    static $base = null;

    if ($base !== null) {
        return $base;
    }

    $scriptDir = rtrim(str_replace('\\', '/', dirname((string) ($_SERVER['SCRIPT_NAME'] ?? '/'))), '/') . '/';
    $uri = (string) parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH);

    if (str_starts_with($uri, $scriptDir)) {
        return $base = $scriptDir;
    }

    $uriParts = explode('/', trim($uri, '/'));
    $shared = [];
    foreach (explode('/', trim($scriptDir, '/')) as $i => $segment) {
        if (($uriParts[$i] ?? null) !== $segment) {
            break;
        }
        $shared[] = $segment;
    }

    return $base = '/' . ($shared ? implode('/', $shared) . '/' : '');
}

/**
 * The only inline scripts on the public site. The Content-Security-Policy
 * allows these two by SHA-256 hash instead of allowing inline script in
 * general, so an injected <script> or onclick= attribute does not run.
 *
 * Editing either string changes its hash: run extras/tools/csp-hashes.php and
 * paste its output into the policy in public/.htaccess, or the browser will
 * block the edited script. The <meta> copy of the policy in head-meta.php is
 * computed from these constants and needs nothing.
 */
const INLINE_SCRIPT_JS_CLASS = "document.documentElement.classList.add('js');";
const INLINE_SCRIPT_ASYNC_CSS = "document.querySelectorAll('link[data-async-css]').forEach(function(l){l.removeAttribute('data-async-css');function on(){l.media='all'}if(l.sheet)on();else l.addEventListener('load',on)});";

/**
 * CSP source list for the inline scripts above: "'sha256-…' 'sha256-…'".
 */
function inlineScriptHashes(): string
{
    return implode(' ', array_map(
        static fn(string $js): string => "'sha256-" . base64_encode(hash('sha256', $js, true)) . "'",
        [INLINE_SCRIPT_JS_CLASS, INLINE_SCRIPT_ASYNC_CSS]
    ));
}

/**
 * A stylesheet that does not block the first paint.
 *
 * media="print" makes the browser fetch the file at normal priority but treat
 * it as irrelevant to the screen, so it is not a render-blocking resource. The
 * script after it flips it to media="all" the moment it arrives, at which point
 * it applies normally. This is the long-standing pattern for the job; the
 * alternative, rel="preload" as="style", has to be swapped to a real
 * stylesheet by script anyway and behaves worse when that script is delayed.
 *
 * Two properties make this safe here:
 *
 *   - The cascade is unaffected. Precedence between stylesheets follows the
 *     document order of the <link> elements, not the order in which they
 *     finish downloading, so styles.css still beats an earlier sheet and is
 *     still beaten by a later one no matter which lands first.
 *
 *   - Nothing above the fold depends on it, because critical.css is inlined
 *     into <head> before this runs. Without that inline block this function
 *     would produce a flash of unstyled content, so the two belong together.
 *
 * The swap used to be an onload="" attribute. The Content-Security-Policy no
 * longer allows inline event handlers, so it is a hashed inline script right
 * after the <link> (INLINE_SCRIPT_ASYNC_CSS). It runs synchronously while the
 * sheet is still downloading, so the load event cannot be missed; if the sheet
 * is somehow already there, l.sheet is set and it switches at once.
 *
 * The <noscript> copy keeps the page styled with JavaScript disabled — the
 * script never runs there, and without the fallback the site would render
 * with the critical subset only.
 */
function asyncStylesheet(string $path): string
{
    $href = htmlspecialchars(asset($path), ENT_QUOTES, 'UTF-8');

    return '<link rel="stylesheet" href="' . $href . '" media="print" data-async-css>'
        . '<script>' . INLINE_SCRIPT_ASYNC_CSS . '</script>'
        . '<noscript><link rel="stylesheet" href="' . $href . '"></noscript>';
}

/**
 * The inlined above-the-fold CSS, as a <style> block.
 *
 * Generated by extras/tools/build-critical-css.php. Returns an empty string if the
 * file is missing, which keeps a page rendering (from the full stylesheet,
 * a little later) rather than fataling on a build step nobody ran.
 */
function criticalCss(): string
{
    static $html = null;

    if ($html !== null) {
        return $html;
    }

    $path = publicPath('css/critical.css');

    if (!is_file($path)) {
        return $html = '';
    }

    // No escaping: this is a generated stylesheet from the repository, not
    // user input. It is checked for the one sequence that could break out of
    // a <style> element, which cannot occur in valid CSS but would be worth
    // knowing about if it ever did.
    $css = (string) file_get_contents($path);

    if (stripos($css, '</style') !== false) {
        return $html = '';
    }

    return $html = "<style>\n" . $css . "\n</style>";
}

/**
 * An <img> tag with srcset, dimensions and the right loading hints.
 *
 * @param string               $src     Path below public/, e.g. 'assets/images/programs/x.jpg'.
 * @param string               $alt     Alt text. Pass '' for a decorative image.
 * @param array<string, mixed> $options
 *     sizes         string  the `sizes` attribute; defaults to '100vw'
 *     class         string  class attribute
 *     lazy          bool    true (default) for loading="lazy", false for eager
 *     priority      bool    true adds fetchpriority="high" and forces eager
 *     width,height  int     override the intrinsic dimensions
 *     attrs         string  raw extra attributes, already escaped
 *     defer         bool    emit data-src/data-srcset instead of src/srcset,
 *                           for images JavaScript decides when to fetch
 */
function imageTag(string $src, string $alt, array $options = []): string
{
    $src = ltrim($src, '/');
    $abs = publicPath($src);

    $priority = (bool) ($options['priority'] ?? false);
    $lazy = $priority ? false : (bool) ($options['lazy'] ?? true);
    $defer = (bool) ($options['defer'] ?? false);

    $width = $options['width'] ?? null;
    $height = $options['height'] ?? null;

    if (($width === null || $height === null) && is_file($abs)) {
        $size = @getimagesize($abs);
        if ($size !== false) {
            $width ??= $size[0];
            $height ??= $size[1];
        }
    }

    $srcset = imageSrcset($src);
    $sizes = htmlspecialchars((string) ($options['sizes'] ?? '100vw'), ENT_QUOTES, 'UTF-8');
    $escSrc = htmlspecialchars($src, ENT_QUOTES, 'UTF-8');

    $attrs = [];

    if ($defer) {
        // A 1x1 transparent GIF holds the src attribute so the browser has
        // nothing to fetch and nothing to draw. Leaving src off entirely also
        // works but makes some browsers report a broken image in the console,
        // and this costs 62 bytes inline.
        $attrs[] = 'src="data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7"';
        $attrs[] = 'data-src="' . $escSrc . '"';

        if ($srcset !== '') {
            $attrs[] = 'data-srcset="' . htmlspecialchars($srcset, ENT_QUOTES, 'UTF-8') . '"';
            $attrs[] = 'data-sizes="' . $sizes . '"';
        }
    } else {
        $attrs[] = 'src="' . $escSrc . '"';

        if ($srcset !== '') {
            $attrs[] = 'srcset="' . htmlspecialchars($srcset, ENT_QUOTES, 'UTF-8') . '"';
            $attrs[] = 'sizes="' . $sizes . '"';
        }
    }

    // Width and height are not cosmetic: without them the browser cannot
    // reserve space before the image arrives, and every element below it jumps
    // when it does. That jump is exactly what Cumulative Layout Shift measures.
    if ($width !== null && $height !== null) {
        $attrs[] = 'width="' . (int) $width . '"';
        $attrs[] = 'height="' . (int) $height . '"';
    }

    $attrs[] = 'alt="' . htmlspecialchars($alt, ENT_QUOTES, 'UTF-8') . '"';

    if ($alt === '') {
        $attrs[] = 'aria-hidden="true"';
    }

    if (!empty($options['class'])) {
        $attrs[] = 'class="' . htmlspecialchars((string) $options['class'], ENT_QUOTES, 'UTF-8') . '"';
    }

    $attrs[] = 'loading="' . ($lazy ? 'lazy' : 'eager') . '"';

    // decoding="async" keeps image decode off the main thread. On the hero,
    // "sync" is the better answer instead: it is the LCP element, and an async
    // decode can land a frame after paint.
    $attrs[] = 'decoding="' . ($priority ? 'sync' : 'async') . '"';

    if ($priority) {
        $attrs[] = 'fetchpriority="high"';
    }

    if (!empty($options['attrs'])) {
        $attrs[] = (string) $options['attrs'];
    }

    return '<img ' . implode(' ', $attrs) . '>';
}

/**
 * srcset built from whichever width variants actually exist on disk.
 *
 * Returns '' when none do, so an image that has not been through the optimiser
 * degrades to a plain <img> rather than a broken srcset pointing at 404s.
 */
function imageSrcset(string $src): string
{
    static $cache = [];

    if (isset($cache[$src])) {
        return $cache[$src];
    }

    $abs = publicPath($src);

    if (!is_file($abs)) {
        return $cache[$src] = '';
    }

    $dir = dirname($src);
    $ext = pathinfo($src, PATHINFO_EXTENSION);
    $base = pathinfo($src, PATHINFO_FILENAME);

    $size = @getimagesize($abs);
    $srcWidth = $size !== false ? $size[0] : 0;

    $entries = [];

    foreach ([480, 768, 1200, 1600] as $width) {
        $rel = ($dir === '.' ? '' : $dir . '/') . "{$base}-{$width}w.{$ext}";
        if (is_file(publicPath($rel))) {
            $entries[] = $rel . ' ' . $width . 'w';
        }
    }

    if ($entries === []) {
        return $cache[$src] = '';
    }

    // The original is the largest candidate, and it needs its true width or the
    // browser will treat it as interchangeable with the last variant and may
    // never pick it on a wide screen.
    if ($srcWidth > 0) {
        $entries[] = $src . ' ' . $srcWidth . 'w';
    }

    return $cache[$src] = implode(', ', $entries);
}
